#[repr(u8)]
pub enum Method {
    Ping = 1,
    Use = 2,
    Set = 3,
    Unset = 4,
    Select = 5,
    Insert = 6,
    Create = 7,
    Update = 8,
    Upsert = 9,
    Merge = 10,
    Patch = 11,
    Delete = 12,
    Version = 13,
    Query = 14,
    Relate = 15,
    Run = 16,
    InsertRelation = 17,
    Sessions = 18,
    Attach = 19,
    Detach = 20,
    Begin = 21,
    Commit = 22,
    Cancel = 23,
    Reset = 24,
}

impl From<Method> for surrealdb_rpc::Method {
    fn from(value: Method) -> Self {
        match value {
            Method::Ping => surrealdb_rpc::Method::Ping,
            Method::Use => surrealdb_rpc::Method::Use,
            Method::Set => surrealdb_rpc::Method::Set,
            Method::Unset => surrealdb_rpc::Method::Unset,
            Method::Select => surrealdb_rpc::Method::Select,
            Method::Insert => surrealdb_rpc::Method::Insert,
            Method::Create => surrealdb_rpc::Method::Create,
            Method::Update => surrealdb_rpc::Method::Update,
            Method::Upsert => surrealdb_rpc::Method::Upsert,
            Method::Merge => surrealdb_rpc::Method::Merge,
            Method::Patch => surrealdb_rpc::Method::Patch,
            Method::Delete => surrealdb_rpc::Method::Delete,
            Method::Version => surrealdb_rpc::Method::Version,
            Method::Query => surrealdb_rpc::Method::Query,
            Method::Relate => surrealdb_rpc::Method::Relate,
            Method::Run => surrealdb_rpc::Method::Run,
            Method::InsertRelation => surrealdb_rpc::Method::InsertRelation,
            Method::Sessions => surrealdb_rpc::Method::Sessions,
            Method::Attach => surrealdb_rpc::Method::Attach,
            Method::Detach => surrealdb_rpc::Method::Detach,
            Method::Begin => surrealdb_rpc::Method::Begin,
            Method::Commit => surrealdb_rpc::Method::Commit,
            Method::Cancel => surrealdb_rpc::Method::Cancel,
            Method::Reset => surrealdb_rpc::Method::Reset,
        }
    }
}
